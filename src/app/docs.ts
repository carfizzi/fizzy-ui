import { Type } from '@angular/core';

export interface ComponentDoc {
  /** The registry name: `npx fizzy-ui add <name>`. */
  name: string;
  title: string;
  description: string;
  /** Registry file the user gets (shared by menu/menubar/context-menu, select/multiselect, dialog/sheet). */
  file: string;
  /** Demo component, the demo's own source (shown as usage) and the registry file's source. */
  load: () => Promise<[Type<unknown>, string, string]>;
  keyboard?: [keys: string, action: string][];
  a11y?: string[];
}

// Text imports go through Angular's `loader: 'text'` import attribute; TypeScript still types them as the module.
const text = (m: unknown) => (m as { default: string }).default;
const all = (demo: Promise<{ Demo: Type<unknown> }>, demoSrc: Promise<unknown>, src: Promise<unknown>) =>
  Promise.all([demo, demoSrc, src]).then(([d, a, b]) => [d.Demo, text(a), text(b)] as [Type<unknown>, string, string]);

